const CUSTOM_SONGS_KEY = "beat-for-beat:custom-songs";

export const getCustomSongs = (): SavedSong[] => {
    if (typeof window === "undefined") return [];
    try {
        const raw = localStorage.getItem(CUSTOM_SONGS_KEY);
        if (!raw) return [];
        return JSON.parse(raw).map((song: any) => ({...song, isCustom: true}));
    } catch (error) {
        console.error("Kunne ikke hente sanger fra localStorage", error);
        return [];
    }
};

export const saveCustomSong = (song: Omit<SavedSong, "id" | "isCustom">): SavedSong => {
    const custom = getCustomSongs();
    const newSong: SavedSong = {
        ...song,
        id: `custom-${Date.now()}-${Math.random().toString(36).slice(2, 7)}`,
        isCustom: true,
    };
    const updated = [...custom, newSong];
    try {
        localStorage.setItem(CUSTOM_SONGS_KEY, JSON.stringify(updated));
    } catch (error) {
        console.error("Kunne ikke lagre sang i localStorage", error);
    }
    return newSong;
};

export const deleteCustomSong = (id: string): void => {
    const custom = getCustomSongs();
    const updated = custom.filter((song) => song.id !== id);
    try {
        localStorage.setItem(CUSTOM_SONGS_KEY, JSON.stringify(updated));
    } catch (error) {
        console.error("Kunne ikke slette sang fra localStorage", error);
    }
};

export const getAllSongs = (): SavedSong[] => {
    return [...PRELOADED_SONGS, ...getCustomSongs()];
};